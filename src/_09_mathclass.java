public class _09_mathclass {

    public static void main(String[] args ){

        System.out.println(Math.PI); // FOR PI
        System.out.println(Math.E); // for EXPONENT

        double result = Math.pow(3,2);// 3²=9
        System.out.println(result);
        double result2 = Math.abs(-56); // absolute
        System.out.println(result2);
        double result3= Math.sqrt(49); // square root
        System.out.println(result3);
        double result4= Math.round(3.50); // rouding off normal way
        System.out.println(result4);
        double result5= Math.ceil(3.50); // ceil for upper value
        System.out.println(result5);
        double result6= Math.floor(3.50); // floor for lower value
        System.out.println(result6);
        double result7= Math.max(50,22); // maximum between these two
        System.out.println(result7);
        double result8= Math.min(50,22); // minimum between these two
        System.out.println(result8);

    }
}
